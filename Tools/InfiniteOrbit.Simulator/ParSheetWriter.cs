using System;
using System.Linq;
using System.Text;
using InfiniteOrbit.GameMath;

namespace InfiniteOrbit.Simulator
{
    /// <summary>Generates docs/PAR.md from the live config and a simulation report. Never edit the output by hand.</summary>
    public sealed class ParSheetWriter
    {
        private readonly GameConfig _c;
        private readonly Report _r;
        private readonly SimulationStats _s;
        private readonly StringBuilder _sb = new StringBuilder();

        public ParSheetWriter(GameConfig config, Report report)
        {
            _c = config;
            _r = report;
            _s = report.Stats;
        }

        private void L(string line = "") => _sb.Append(line).Append('\n');

        private string Code(Symbol s) => _c.Info(s).Code;

        private static string Pct(double p) => p >= 1e-6 ? p.ToString("P5") : (p * 100).ToString("0.###E+0") + "%";

        public string Write()
        {
            Header();
            Summary();
            Rules();
            Paytable();
            Paylines();
            SymbolWeights("Base game", _c.BaseReels, InfiniteOrbitMath.BaseCounts);
            SymbolWeights("Free spins", _c.FreeSpinReels, InfiniteOrbitMath.FreeSpinCounts);
            FeatureOdds();
            FreeSpins();
            HoldAndSpin();
            SimulationResults();
            Strips("Base game", _c.BaseReels);
            Strips("Free spins", _c.FreeSpinReels);
            Reproduce();
            return _sb.ToString().Replace(" %", "%");
        }

        private void Header()
        {
            L($"# {_c.GameName} — PAR Sheet");
            L();
            L("> Generated by `Tools/InfiniteOrbit.Simulator` from `InfiniteOrbitMath.CreateConfig()`. Do not edit by hand;");
            L("> re-run the simulator (see *Reproducing* at the end). Demo game: fake credits only, no real-money play.");
            L();
            L("| Item | Value |");
            L("|---|---|");
            L($"| Math version | `{_c.Version}` |");
            L("| Layout | 5 reels × 3 rows, 25 fixed lines, left to right |");
            L($"| Bet levels (total bet, credits) | {string.Join(" / ", Enumerable.Range(0, _c.LineBets.Length).Select(_c.TotalBetForLevel))} |");
            L($"| Simulation | {_s.Rounds:N0} rounds, seed `{_r.Seed}`, bet level {_r.BetLevel} ({_r.Bet} credits) |");
            L();
        }

        private void Summary()
        {
            L("## 1. Summary");
            L();
            L("| Metric | Simulated | Exact / design |");
            L("|---|---:|---:|");
            L($"| **Total RTP** | **{_s.Rtp:P3}** (95% CI ± {_s.Rtp95HalfWidth:P3}) | target 94.000% – 96.000% |");
            L($"| Base game line wins | {_s.RtpOf(_s.BaseLineWin):P3} | {_r.ExactLineRtp:P3} |");
            L($"| Base game scatter pays | {_s.RtpOf(_s.BaseScatterWin):P3} | {_r.ExactScatterRtp:P3} |");
            L($"| Free spins | {_s.RtpOf(_s.FreeSpinsWin):P3} | simulation only |");
            L($"| Orbit Lock (hold & spin) | {_s.RtpOf(_s.HoldAndSpinWin):P3} | simulation only |");
            L($"| &nbsp;&nbsp;of which jackpots | {_s.RtpOf(_s.HoldAndSpinJackpotWin):P3} | |");
            L($"| Hit frequency (round pays > 0) | {_s.HitFrequency:P3} ({Report.OneIn(_s.HitFrequency)}) | |");
            L($"| Free spins trigger | {SimulationStats.OneIn(_s.FreeSpinTriggers, _s.Rounds)} | {Report.OneIn(_r.ExactFreeSpinTrigger)} |");
            L($"| Orbit Lock trigger | {SimulationStats.OneIn(_s.HoldAndSpinTriggers, _s.Rounds)} | {Report.OneIn(_r.ExactHoldAndSpinTrigger)} |");
            L($"| Any feature trigger | {SimulationStats.OneIn(_s.FreeSpinTriggers + _s.HoldAndSpinTriggers - _s.BothFeatures, _s.Rounds)} | |");
            L($"| Average win per round | {_s.MeanMultiple:F4}× bet | |");
            L($"| Average win when a round pays | {_s.AverageWinMultipleWhenHit:F3}× bet | |");
            L($"| Max win observed | {_s.MaxWinMultiple:N1}× bet | no win cap |");
            L($"| Standard deviation | {_s.StdDev:F2} | |");
            L($"| Volatility index (90%, 1.645σ) | {_r.VolatilityIndex90:F2} | moderate-high |");
            L();
        }

        private void Rules()
        {
            var fs = _c.FreeSpins;
            var hs = _c.HoldAndSpin;
            L("## 2. Game rules");
            L();
            L("- Line wins pay left to right from reel 1 on consecutive reels; highest win per line only. Line pays are multiples of the **line bet** (total bet / 25).");
            L($"- **{_c.Info(Symbol.Wild).Name}** (wild) appears on reels 2–4 only and substitutes for all symbols except **{_c.Info(Symbol.Scatter).Name}** and **{_c.Info(Symbol.Orb).Name}**. It has no pay of its own.");
            L($"- **{_c.Info(Symbol.Scatter).Name}** (scatter) pays anywhere in multiples of **total bet**. Line and scatter wins add.");
            L($"- 3 / 4 / 5 scatters award {fs.Awards[3]} / {fs.Awards[4]} / {fs.Awards[5]} free spins. Retriggers add the same amounts.");
            L($"- Free-spin multiplier starts at {fs.StartMultiplier}×, applies to all wins of the spin, and rises by {fs.MultiplierStep} after every free spin that pays, up to {fs.MaxMultiplier}×.");
            L($"- Free spins use their own reel strips (no orbs). Engineering cap: {fs.MaxTotalSpins} free spins per feature (hit {_s.FreeSpinCapHits:N0} times in this run).");
            L($"- **{_c.Info(Symbol.Orb).Name}**: {hs.TriggerCount}+ anywhere on a base-game spin start **Orbit Lock** with {hs.Respins} respins. Orbs hold; each new orb resets respins to {hs.Respins}.");
            L($"- Each orb shows a credit prize or a Mini/Minor/Major jackpot. Filling all {GameConfig.Cells} positions also awards the Grand.");
            L($"- Fixed jackpots (× total bet): Mini {hs.MiniMultiple}, Minor {hs.MinorMultiple}, Major {hs.MajorMultiple}, Grand {hs.GrandMultiple}.");
            L("- If a base spin triggers both features, Orbit Lock plays first, then free spins. Every outcome is decided before reels animate.");
            L($"- Celebration tiers (presentation only): Big ≥ {_c.BigWin.Big}×, Mega ≥ {_c.BigWin.Mega}×, Epic ≥ {_c.BigWin.Epic}× total bet.");
            L();
        }

        private void Paytable()
        {
            L("## 3. Symbols and paytable");
            L();
            L("| ID | Code | Symbol | Type | 3 | 4 | 5 |");
            L("|---:|---|---|---|---:|---:|---:|");
            foreach (var s in _c.Symbols)
            {
                string p3 = "", p4 = "", p5 = "";
                if (s.Kind == SymbolKind.Scatter)
                {
                    p3 = $"{_c.ScatterPays[3]}× TB"; p4 = $"{_c.ScatterPays[4]}× TB"; p5 = $"{_c.ScatterPays[5]}× TB";
                }
                else if (s.PaysOnLines)
                {
                    p3 = s.Pays[3].ToString(); p4 = s.Pays[4].ToString(); p5 = s.Pays[5].ToString();
                }
                else
                {
                    p3 = p4 = p5 = "—";
                }
                L($"| {(int)s.Id} | `{s.Code}` | {s.Name} | {s.Kind} | {p3} | {p4} | {p5} |");
            }
            L();
            L("Line pays are in line-bet multiples; TB = total bet.");
            L();
        }

        private void Paylines()
        {
            L("## 4. Paylines");
            L();
            L("Rows: 0 = top, 1 = middle, 2 = bottom.");
            L();
            L("| Line | Rows | Shape |");
            L("|---:|---|---|");
            foreach (var line in _c.Paylines)
            {
                string shape = string.Join("", line.Rows.Select(r => r == 0 ? "▔" : r == 1 ? "─" : "▁"));
                L($"| {line.Index + 1} | {string.Join(" ", line.Rows)} | `{shape}` |");
            }
            L();
        }

        private void SymbolWeights(string title, ReelSet reels, int[][] counts)
        {
            L($"## {(title.StartsWith("Base") ? 5 : 6)}. Symbol weights — {title.ToLowerInvariant()} reels");
            L();
            L("Counts of each symbol on each strip (all stops equally likely). Percent = count / strip length.");
            L();
            L("| Symbol | Reel 1 | Reel 2 | Reel 3 | Reel 4 | Reel 5 |");
            L("|---|---:|---:|---:|---:|---:|");
            for (int s = 0; s < InfiniteOrbitMath.StripSymbols.Length; s++)
            {
                var sym = InfiniteOrbitMath.StripSymbols[s];
                var cells = Enumerable.Range(0, GameConfig.Reels)
                    .Select(r => counts[r][s] == 0 ? "—" : $"{counts[r][s]} ({(double)counts[r][s] / reels[r].Length:P1})");
                L($"| {_c.Info(sym).Name} `{Code(sym)}` | {string.Join(" | ", cells)} |");
            }
            L($"| **Strip length** | {string.Join(" | ", Enumerable.Range(0, GameConfig.Reels).Select(r => $"**{reels[r].Length}**"))} |");
            L();
            long combos = 1;
            for (int r = 0; r < GameConfig.Reels; r++) combos *= reels[r].Length;
            L($"Total stop combinations: {combos:N0}.");
            L();
        }

        private void FeatureOdds()
        {
            L("## 7. Feature odds (exact, base game)");
            L();
            L("Computed by convolving each reel's distribution of visible symbols over all stops.");
            L();
            L("| Scatters on screen | Probability | Odds | Pays | Free spins |");
            L("|---:|---:|---:|---:|---:|");
            for (int n = 0; n <= GameConfig.Reels; n++)
                L($"| {n} | {_r.ScatterDistribution[n]:P5} | {Report.OneIn(_r.ScatterDistribution[n])} | {_c.ScatterPays[n]}× TB | {_c.FreeSpins.Awards[n]} |");
            L($"| **3+** | **{_r.ExactFreeSpinTrigger:P5}** | **{Report.OneIn(_r.ExactFreeSpinTrigger)}** | | |");
            L();
            L("| Orbs on screen | Probability | Odds |");
            L("|---:|---:|---:|");
            for (int n = 0; n <= GameConfig.Cells; n++)
            {
                if (_r.OrbDistribution[n] <= 0) continue;
                L($"| {n} | {Pct(_r.OrbDistribution[n])} | {Report.OneIn(_r.OrbDistribution[n])} |");
            }
            L($"| **{_c.HoldAndSpin.TriggerCount}+** | **{_r.ExactHoldAndSpinTrigger:P5}** | **{Report.OneIn(_r.ExactHoldAndSpinTrigger)}** |");
            L();
        }

        private void FreeSpins()
        {
            L("## 8. Free spins");
            L();
            L("| Metric | Value |");
            L("|---|---:|");
            L($"| Triggers | {_s.FreeSpinTriggers:N0} ({SimulationStats.OneIn(_s.FreeSpinTriggers, _s.Rounds)}) |");
            for (int n = 3; n <= GameConfig.Reels; n++)
                L($"| &nbsp;&nbsp;via {n} scatters ({_c.FreeSpins.Awards[n]} spins) | {_s.FreeSpinTriggersByScatters[n]:N0} ({SimulationStats.OneIn(_s.FreeSpinTriggersByScatters[n], _s.Rounds)}) |");
            L($"| Average spins played per feature | {_r.FreeSpinAverageSpins:F2} |");
            L($"| Retriggers per feature | {_r.PerTrigger(_s.FreeSpinRetriggers, _s.FreeSpinTriggers):F4} |");
            L($"| Features reaching {_c.FreeSpins.MaxMultiplier}× multiplier | {_r.PerTrigger(_s.FreeSpinMaxMultiplierReached, _s.FreeSpinTriggers):P2} |");
            L($"| Average award | {_r.FreeSpinAverageAward:F2}× bet |");
            L($"| Largest award | {_s.FreeSpinMaxWinMultiple:N1}× bet |");
            L($"| Free-spin reel line RTP per spin at 1× (exact) | {_r.FreeSpinReelLineRtp:P3} |");
            L($"| Spin-cap hits | {_s.FreeSpinCapHits:N0} |");
            L();
        }

        private void HoldAndSpin()
        {
            var hs = _c.HoldAndSpin;
            double land = (double)hs.OrbWeight / (hs.OrbWeight + hs.BlankWeight);
            L("## 9. Orbit Lock (hold & spin)");
            L();
            L($"During respins every empty cell spins an independent single-position reel: Orb {hs.OrbWeight} : Blank {hs.BlankWeight} (P(orb) = {land:P3}).");
            L();
            L("**Orb prize table** (same table for base-game orbs and respin orbs; credit prizes in line-bet multiples)");
            L();
            L("| Prize | × total bet | Weight | Probability |");
            L("|---|---:|---:|---:|");
            var table = hs.Prizes;
            for (int i = 0; i < table.Count; i++)
            {
                var p = table[i];
                string label = p.IsJackpot ? p.Kind.ToString() : $"{p.LineBetMultiple}× line bet";
                double x = p.IsJackpot ? hs.JackpotMultiple(p.Kind) : (double)p.LineBetMultiple / _c.LineCount;
                L($"| {label} | {x:0.##} | {table.WeightAt(i)} | {table.ProbabilityAt(i):P3} |");
            }
            L($"| **Total / mean** | **{_r.MeanOrbPrize:F3}** | **{table.TotalWeight}** | 100% |");
            L();
            L("| Metric | Value |");
            L("|---|---:|");
            L($"| Triggers | {_s.HoldAndSpinTriggers:N0} ({SimulationStats.OneIn(_s.HoldAndSpinTriggers, _s.Rounds)}) |");
            L($"| Average orbs at end | {_r.HoldAndSpinAverageOrbs:F2} of {GameConfig.Cells} |");
            L($"| Average respins played | {_r.HoldAndSpinAverageRespins:F2} |");
            L($"| Average award | {_r.HoldAndSpinAverageAward:F2}× bet |");
            L($"| Largest award | {_s.HoldAndSpinMaxWinMultiple:N1}× bet |");
            L();
            L("| Jackpot | × total bet | Hits | Per feature | Per base spin |");
            L("|---|---:|---:|---:|---:|");
            foreach (var kind in new[] { OrbPrizeKind.Mini, OrbPrizeKind.Minor, OrbPrizeKind.Major, OrbPrizeKind.Grand })
            {
                long hits = _s.JackpotHits[(int)kind];
                L($"| {kind} | {hs.JackpotMultiple(kind)} | {hits:N0} | {_r.PerTrigger(hits, _s.HoldAndSpinTriggers):F4} | {SimulationStats.OneIn(hits, _s.Rounds)} |");
            }
            L();
        }

        private void SimulationResults()
        {
            L("## 10. Simulation results");
            L();
            L($"{_s.Rounds:N0} rounds at {_r.Bet} credits, seed `{_r.Seed}`, {Simulation.ChunkSize:N0}-round chunks with independent derived RNG streams (identical results on any thread count).");
            L();
            L("### Win distribution (total round win, × total bet)");
            L();
            L("| Bucket | Rounds | Probability | Odds | RTP contribution |");
            L("|---|---:|---:|---:|---:|");
            for (int i = 0; i < _s.BucketCounts.Length; i++)
            {
                double p = _r.PerRound(_s.BucketCounts[i]);
                L($"| {SimulationStats.BucketLabel(i)} | {_s.BucketCounts[i]:N0} | {p:P4} | {Report.OneIn(p)} | {_s.BucketWin[i] / _s.Rounds:P3} |");
            }
            L();
            L("```");
            double maxP = 0;
            for (int i = 1; i < _s.BucketCounts.Length; i++) maxP = Math.Max(maxP, _r.PerRound(_s.BucketCounts[i]));
            for (int i = 1; i < _s.BucketCounts.Length; i++)
            {
                double p = _r.PerRound(_s.BucketCounts[i]);
                int bar = (int)Math.Round(50 * Math.Sqrt(p / maxP));
                L($"{SimulationStats.BucketLabel(i),-16} {new string('█', Math.Max(bar, p > 0 ? 1 : 0)),-50} {p:P4}");
            }
            L("(winning rounds only; bar length ∝ √probability)");
            L("```");
            L();
            L("### Celebration tiers");
            L();
            L("| Tier | Threshold | Rounds | Odds |");
            L("|---|---:|---:|---:|");
            L($"| Big | ≥ {_c.BigWin.Big}× | {_s.BigWinCounts[(int)BigWinTier.Big]:N0} | {SimulationStats.OneIn(_s.BigWinCounts[(int)BigWinTier.Big], _s.Rounds)} |");
            L($"| Mega | ≥ {_c.BigWin.Mega}× | {_s.BigWinCounts[(int)BigWinTier.Mega]:N0} | {SimulationStats.OneIn(_s.BigWinCounts[(int)BigWinTier.Mega], _s.Rounds)} |");
            L($"| Epic | ≥ {_c.BigWin.Epic}× | {_s.BigWinCounts[(int)BigWinTier.Epic]:N0} | {SimulationStats.OneIn(_s.BigWinCounts[(int)BigWinTier.Epic], _s.Rounds)} |");
            L();
        }

        private void Strips(string title, ReelSet reels)
        {
            L($"## {(title.StartsWith("Base") ? 11 : 12)}. Reel strips — {title.ToLowerInvariant()}");
            L();
            L($"Stop index → symbol code. Layout seed `0x{InfiniteOrbitMath.StripLayoutSeed:X}`; the stop shown on the top row is the reported stop.");
            L();
            int max = Enumerable.Range(0, GameConfig.Reels).Max(r => reels[r].Length);
            L("| Stop | Reel 1 | Reel 2 | Reel 3 | Reel 4 | Reel 5 |");
            L("|---:|---|---|---|---|---|");
            for (int i = 0; i < max; i++)
            {
                var cells = Enumerable.Range(0, GameConfig.Reels).Select(r => i < reels[r].Length ? Code(reels[r].Symbols[i]) : "");
                L($"| {i} | {string.Join(" | ", cells)} |");
            }
            L();
        }

        private void Reproduce()
        {
            L("## Reproducing");
            L();
            L("```bash");
            L("cd Tools/InfiniteOrbit.Simulator");
            L($"dotnet run -c Release -- --spins {_s.Rounds} --seed {_r.Seed} --bet-level {_r.BetLevel} --par ../../docs/PAR.md");
            L("```");
        }
    }
}
